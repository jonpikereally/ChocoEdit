#!/bin/zsh
# Build a release: universal (Apple Silicon + Intel) app with an installer,
# written to updates/ChocoEdit.zip + updates/latest.json. Committing and
# pushing updates/ ships it: every installed copy's "Check for Updates" reads
# latest.json from this repo on GitHub.
#
# Bump VERSION, write the notes in RELEASE_NOTES.txt (or pass UPDATE_NOTES),
# then: ./release.sh
# (without UPDATE_NOTES the notes come from RELEASE_NOTES.txt)
set -e
cd "$(dirname "$0")"
VERSION=$(cat VERSION)
REPO="${REPO:-jonpikereally/ChocoEdit}"
# Every error code used in the app and installer must be on the public error list.
missing=$(grep -ohE 'CE-[0-9]{3}' Sources/ChocoEdit/*.swift Tools/chocoprobe/main.swift release.sh install.sh | sort -u | while read -r c; do
  grep -q "^| $c |" ERRORS.md || echo "$c"
done)
if [[ -n "$missing" ]]; then
  echo "Error codes missing from ERRORS.md: $missing" >&2
  exit 1
fi
if [[ -z "${UPDATE_NOTES:-}" && -f RELEASE_NOTES.txt ]]; then
  UPDATE_NOTES=$(<RELEASE_NOTES.txt)
fi
BUILT=$(date "+%b %d, %H:%M")
FEED="${UPDATE_FEED-https://raw.githubusercontent.com/$REPO/main/updates/latest.json}"
cat > Sources/ChocoEdit/Version.swift <<SWIFT
// Generated by build.sh / release.sh — do not edit.
enum AppVersion {
    static let version = "$VERSION"
    static let built = "$BUILT"
    static let repo = "$REPO"
    static let updateFeed = "$FEED"
}
SWIFT
CACHE="${TMPDIR:-/tmp}/chocoedit-modcache"
mkdir -p "$CACHE"
echo "Building arm64…"
swiftc -O -target arm64-apple-macos13 -module-cache-path "$CACHE" \
  -o "$CACHE/ChocoEdit-arm64" Sources/ChocoEdit/*.swift
echo "Building x86_64…"
swiftc -O -target x86_64-apple-macos13 -module-cache-path "$CACHE-x86" \
  -o "$CACHE/ChocoEdit-x86_64" Sources/ChocoEdit/*.swift

DIST="$CACHE/dist"
rm -rf "$DIST"
APP="$DIST/ChocoEdit/ChocoEdit.app"
mkdir -p "$APP/Contents/MacOS"
lipo -create -output "$APP/Contents/MacOS/ChocoEdit" \
  "$CACHE/ChocoEdit-arm64" "$CACHE/ChocoEdit-x86_64"
cp Resources/Info.plist "$APP/Contents/Info.plist"
mkdir -p "$APP/Contents/Resources"
cp Resources/AppIcon.icns "$APP/Contents/Resources/AppIcon.icns"
/usr/libexec/PlistBuddy -c "Set :CFBundleShortVersionString $VERSION" "$APP/Contents/Info.plist"
codesign --force --sign - "$APP"

cat > "$DIST/ChocoEdit/Install ChocoEdit.command" <<INSTALL
#!/bin/bash
# ChocoEdit installer — copies the app to ~/Applications and launches it.
cd "\$(dirname "\$0")"
fail() {
  echo
  echo "Error \$1: \$2"
  echo "Look up this code on the ChocoEdit error list:"
  echo "  https://github.com/$REPO/blob/main/ERRORS.md"
  echo "(You can also give that page to an AI assistant for help.)"
  exit 1
}
echo "Installing ChocoEdit…"
mkdir -p ~/Applications || fail CE-601 "Couldn't create ~/Applications."
rm -rf ~/Applications/ChocoEdit.app
ditto --norsrc ChocoEdit.app ~/Applications/ChocoEdit.app \\
  || fail CE-601 "Couldn't copy ChocoEdit into ~/Applications."
# Clear the download quarantine and re-sign locally so macOS trusts it on this Mac.
xattr -dr com.apple.quarantine ~/Applications/ChocoEdit.app 2>/dev/null
codesign --force --sign - ~/Applications/ChocoEdit.app 2>/dev/null \\
  || fail CE-602 "Couldn't sign ChocoEdit for this Mac."
open ~/Applications/ChocoEdit.app \\
  || fail CE-603 "ChocoEdit was installed but couldn't be opened. Open it from ~/Applications yourself."
echo
echo "Done! Plug in your Chocolate Plus with USB, quit CubeSuite, and click Read from Pedal."
INSTALL
chmod +x "$DIST/ChocoEdit/Install ChocoEdit.command"

cat > "$DIST/ChocoEdit/README.txt" <<README
ChocoEdit v$VERSION — an editor for the M-VAVE Chocolate Plus MIDI foot controller (macOS 13+)
https://github.com/$REPO

INSTALL
1. Double-click "Install ChocoEdit.command".
   If macOS blocks it: right-click it, choose Open, then Open again.

USE
1. Plug the pedal in with a USB-C data cable and switch it on. Quit CubeSuite.
2. Click Read from Pedal. Pick a group, click a switch, edit its messages.
3. Click Write to Pedal. ChocoEdit backs up the pedal's current settings to
   ~/Documents/ChocoEdit Backups first, writes only what changed, and reads it
   back to check.

ChocoEdit isn't made or supported by M-VAVE. It speaks the same protocol as
their CubeSuite app.

PRIVACY
ChocoEdit talks only to the pedal over MIDI. No accounts, no analytics. The
only thing it fetches from the internet is a small version file from the
GitHub repo above, to see whether an update exists.
README

mkdir -p updates
(cd "$DIST" && ditto -c -k --norsrc --noextattr --noqtn --keepParent ChocoEdit "$OLDPWD/updates/ChocoEdit.zip.tmp")
mv -f updates/ChocoEdit.zip.tmp updates/ChocoEdit.zip
# Manifest last, so a checking app never sees it pointing at a half-written zip.
/usr/bin/python3 -c 'import json,sys; print(json.dumps({"version": sys.argv[1], "url": "ChocoEdit.zip", "notes": sys.argv[2]}))' \
  "$VERSION" "${UPDATE_NOTES:-}" > updates/latest.json.tmp
mv -f updates/latest.json.tmp updates/latest.json

./build.sh >/dev/null
echo "Release v$VERSION written to updates/. Ship it with:"
echo "  git add -A && git commit -m \"Release v$VERSION\" && git push"
